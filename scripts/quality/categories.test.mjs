import { test } from 'node:test'
import { strict as assert } from 'node:assert'
import { categories, classify } from './categories.mjs'

void test('roadmap rows and limits follow first-match order', () => {
  const fixtures = [
    ['x/utils/use-x.ts', 'util', 150, 40, 5],
    ['x/use-x.ts', 'hook', 200, 60, 5],
    ['x/src/A.tsx', 'component', 400, 80, 3],
    ['x/src/a.ts', 'module', 400, 80, 5],
    ['x/scripts/a.mjs', 'script', 400, 80, 5],
    ['x/test/a.test.ts', 'test', 750, 120, 5],
    ['x/types/a.ts', 'types', 1000, null, null],
    ['x/generated/a.ts', 'table', 1000, null, null],
    ['crates/a/src/a.rs', 'rust', 400, 80, 7],
  ]
  assert.equal(fixtures.length, categories.length)
  for (const [path, name, file, fn, params] of fixtures) {
    const category = classify(path)
    assert.deepEqual(
      [category.name, category.file, category.function, category.params],
      [name, file, fn, params],
    )
  }
  assert.equal(classify('unknown.txt'), undefined)
})

void test('tracked shapes and overlaps obey the table order', () => {
  for (const [path, expected] of [
    ['packages/warp-core/styles/app/tokens.css', 'table'],
    ['crates/weft-compiler/tests/compile.rs', 'table'],
    ['packages/core/vitest.config.ts', 'script'],
    ['tsconfig.base.json', 'script'],
    ['packages/start/test/fixtures/app/weft.config.ts', 'script'],
    ['packages/a/src/types.ts', 'module'],
    ['packages/a/src/foo-state.ts', 'hook'],
  ])
    assert.equal(classify(path)?.name, expected, path)
})

void test('generated markers enter the table at its ordered position', () => {
  const header =
    '// Generated by spikes/native/scripts/gen-protocol.mjs from protocol/ops.json. Do not edit.\n'
  assert.equal(classify('crates/weft-layout/src/protocol.rs', { content: header }).name, 'table')
  assert.equal(classify('packages/a/src/generated/file.ts', { content: header }).name, 'module')
  assert.equal(
    classify('assets/output.css', { content: '/* generated from tokens by split: do not edit */' })
      .name,
    'table',
  )
  assert.equal(classify('assets/output.gen.css').name, 'table')
  assert.equal(
    classify('crates/a/src/ordinary.rs', { content: '// This tool generated by users\n' }).name,
    'rust',
  )
})

void test('only the Pretext vendor prefix is excluded', () => {
  assert.equal(classify('packages/text/vendor/pretext/src/a.ts'), undefined)
  assert.equal(classify('packages/text/vendor/pretext-other/src/a.ts')?.name, 'module')
  assert.equal(classify('packages/text/src/a.ts')?.name, 'module')
})

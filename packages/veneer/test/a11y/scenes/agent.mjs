// What the a11y suite does on ?part=agent. `audit(label)` runs axe on the page as it is.
export default async function (page, audit, url, settle) {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto(`${url}?part=agent`)
  await settle(page)
  await audit('agent')
  await page
    .getByRole('button', { name: /^Model:/ })
    .first()
    .click()
  await audit('model picker open')
  await page.keyboard.press('Escape')
  const box = page.getByRole('textbox', { name: 'Message the assistant' }).first()
  await box.fill('/')
  await audit('slash commands open')
  await box.fill('')
  await page.getByRole('tab', { name: 'Trace' }).click()
  await audit('trace tab')
  await page.getByRole('tab', { name: 'Code' }).click()
  await audit('artifact code')
  await page.getByRole('tab', { name: 'Versions' }).click()
  await audit('artifact versions')
  await page.getByRole('button', { name: 'Start dictation' }).click()
  await audit('speech unsupported or blocked')
  await page.getByRole('button', { name: 'Bad answer' }).first().click()
  await audit('feedback reason open')
  await page.keyboard.press('Escape')
  await page.goto(`${url}?part=agent&approval`)
  await settle(page)
  await audit('approval')
  const args = page.getByRole('textbox', { name: 'Arguments · editable' }).first()
  await args.fill('{ "path": "other.ts" }')
  await audit('approval with an edit')
  await page.setViewportSize({ width: 390, height: 780 })
  await page.goto(`${url}?part=agent`)
  await settle(page)
  await audit('agent at 390')
  await page.setViewportSize({ width: 1280, height: 800 })
}

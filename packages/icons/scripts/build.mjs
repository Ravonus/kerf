// art/*.mjs → src/gen/*: every icon and variant from the one source, so the exports and their types can't drift.
//   node scripts/build.mjs           write
//   node scripts/build.mjs --check   exit 1 if src/gen is stale
import { mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { cells, outline, pixel } from './draw.mjs'
import { dither, enclosed, hollow, rasterize, shaded, solid } from './raster.mjs'

const dir = new URL('../art/', import.meta.url)
export async function load() {
  const out = {}
  for (const f of readdirSync(dir).filter(f => f.endsWith('.mjs')).sort()) {
    const set = (await import(new URL(f, dir))).default
    for (const [name, value] of Object.entries(set)) {
      if (out[name]) throw new Error(`${name} twice`)
      out[name] = value
    }
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)))
}
const title = name => name.replace(/(^|-)(.)/g, (_, __, c) => c.toUpperCase())
export const pascal = name => `Icon${title(name)}`
/** The one naming scheme: `XIcon`, `XIconHollow`, `XIconSolid`, `XIconDither`. Tiers are a prop, not a name. */
export const exportName = (name, variant = '') => `${title(name)}Icon${variant}`
export const VARIANTS = ['Hollow', 'Solid', 'Dither']
export const DITHER = 'checker'

/** The pixel grid: drawn by hand, or landed on the grid from the outline spec. */
export const gridOf = (name, [spec, art]) => (art ? pixel(art, name).grid : shaded(rasterize(spec).grid))

const vivid = (grid, t = '') => {
  const p = cells(grid)
  return `<path${t} data-p="" d="${p.ink}"/>` + (p.shade ? `<path${t} data-p="s" d="${p.shade}"/>` : '')
}
const dithered = (grid, t = '') => `<path${t} data-p="" d="${cells(dither(grid, DITHER)).both}"/>`
const filled = (spec, tier, t) => {
  const { body, weft } = outline(spec, tier), r = rasterize(spec), inner = enclosed(r.body)
  const cut = r.weft.flatMap((row, y) => row.map((c, x) => c === '#' && inner[y][x])).filter(Boolean).length > 0
  return (body ? `<path${t} data-s="" d="${body}"/>` : '') + (weft ? `<path${t} ${cut ? 'data-k=""' : 'data-w=""'} d="${weft}"/>` : '')
}

/** What one icon needs: its outline, and each pixel drawing, as the strings exports are built from. */
export function fragments(name, entry) {
  const [spec] = entry, grid = gridOf(name, entry)
  const q = outline(spec, 'quiet'), b = outline(spec, 'balanced')
  const pair = (x, y, w) => (!x && !y ? '' : x === y ? `<path data-t="o"${w} d="${x}"/>` : `<path data-t="q"${w} d="${x}"/><path data-t="b"${w} d="${y}"/>`)
  const v = ' data-t="v"'
  return {
    line: pair(q.body, b.body, '') + pair(q.weft, b.weft, ' data-w=""'),
    vivid: vivid(grid, v),
    hollow: vivid(hollow(grid), v),
    solid: filled(spec, 'quiet', ' data-t="q"') + filled(spec, 'balanced', ' data-t="b"') + vivid(solid(grid), v),
    dither: dithered(grid, v),
  }
}

/** The drawing a tier shows, for the sheet and the tests. */
export function draw(name, entry, tier = 'all', variant = '') {
  const f = fragments(name, entry)
  const all = variant === 'Solid' ? f.solid : f.line + (variant === 'Hollow' ? f.hollow : variant === 'Dither' ? f.dither : f.vivid)
  return all
}

const head = '// Generated by scripts/build.mjs from art/*.mjs: do not edit.\n'
const quote = s => `'${s}'`
function file(icons) {
  let out = `${head}import { icon } from '../svg'\nimport * as self from './all'\nimport '../tiers.css'\n\nexport { iconSet } from '../set'\nexport type { IconComponent, IconProps } from '../svg'\nexport default self\n\n`
  let i = 0
  for (const [name, entry] of Object.entries(icons)) {
    const f = fragments(name, entry), id = `_${(i++).toString(36)}`, X = exportName(name), S = title(name)
    out += `const ${id}=${quote(f.line)}\n`
    out += `export const ${X} = /*#__PURE__*/ icon(${id},${quote(f.vivid)})\n`
    out += `export const ${X}Hollow = /*#__PURE__*/ icon(${id},${quote(f.hollow)})\n`
    out += `export const ${X}Solid = /*#__PURE__*/ icon(${quote(f.solid)})\n`
    out += `export const ${X}Dither = /*#__PURE__*/ icon(${id},${quote(f.dither)})\n`
    out += `export { ${X} as ${pascal(name)}, ${X} as ${S}, ${X}Hollow as ${S}Hollow, ${X}Solid as ${S}Solid, ${X}Dither as ${S}Dither }\n`
  }
  return out
}

export async function outputs() {
  const icons = await load()
  return {
    'all.tsx': file(icons),
    'names.ts': `${head}export const names = ${JSON.stringify(Object.keys(icons))} as const\nexport type IconName = (typeof names)[number]\nexport type IconVariant = 'hollow' | 'solid' | 'dither'\n`,
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await outputs()
  const gen = new URL('../src/gen/', import.meta.url)
  const check = process.argv.includes('--check')
  mkdirSync(gen, { recursive: true })
  const stale = []
  for (const [f, text] of Object.entries(files)) {
    if (!check) { writeFileSync(new URL(f, gen), text); continue }
    let was = ''
    try { was = readFileSync(new URL(f, gen), 'utf8') } catch {}
    if (was !== text) stale.push(f)
  }
  if (stale.length) { console.error(`src/gen is stale (${stale.join(', ')}): run node scripts/build.mjs`); process.exit(1) }
  console.log(`${files['names.ts'].match(/","/g).length + 1} icons`)
}

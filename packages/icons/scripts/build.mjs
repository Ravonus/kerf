// art/*.mjs → src/gen/*: every icon and variant from the one source, so the exports and their types can't drift.
//   node scripts/build.mjs           write
//   node scripts/build.mjs --check   exit 1 if src/gen is stale
import { mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ACTIONS from '../art/actions/index.mjs'
import { acting, forms } from './forms.mjs'

const dir = new URL('../art/', import.meta.url)
export async function load() {
  const out = {}
  for (const f of readdirSync(dir)
    .filter((n) => n.endsWith('.mjs'))
    .sort()) {
    const set = (await import(new URL(f, dir))).default
    for (const [name, value] of Object.entries(set)) {
      if (out[name]) throw new Error(`${name} twice`)
      out[name] = value
    }
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)))
}
const title = (name) => name.replace(/(^|-)(.)/g, (_, __, c) => c.toUpperCase())
/** The one naming scheme: `XIcon` is hollow, the default; `XIconHollow` says so; `XIconSolid` is the other form. Tiers are a prop. */
export const exportName = (name, variant = '') => `${title(name)}Icon${variant}`

/** The stylesheet for one action. warp's motion dial sets the duration, so reduced motion ends it before it starts. */
function actionCss(name) {
  const a = ACTIONS[name],
    act = (t) => `svg[data-act~="${t}"]`
  const trigger = `:is(${act('hover')}:hover,:hover>${act('hover')},${act('focus')}:focus-visible,:focus-visible>${act('focus')},${act('press')}:active,:active>${act('press')},${act('on')})`
  const box = a.origin ? `transform-box:view-box;transform-origin:${a.origin};` : ''
  const run = `animation:weft-${name} calc(${a.ms}ms*var(--warp-motion-scale,1)) ease-out`
  return `/* Generated by scripts/build.mjs: do not edit. */
@layer warp.components {
@media (prefers-reduced-motion:no-preference) {
${trigger} [data-a="${name}"] { ${box}${run}; }
${trigger} [data-a="${name}"][data-t="v"] { animation-name:weft-${name}-v;animation-timing-function:${a.steps}; }
${
  a.loop
    ? `svg[data-act~="on"] [data-a="${name}"] { animation-iteration-count:infinite;animation-timing-function:linear;animation-play-state:var(--warp-loop-play,running); }
svg[data-act~="on"] [data-a="${name}"][data-t="v"] { animation-timing-function:${a.steps}; }
`
    : ''
}}
${
  a.draw
    ? `[data-a="${name}"] path { stroke-dasharray:1; }
`
    : ''
}}
@keyframes weft-${name} { ${a.keyframes} }
@keyframes weft-${name}-v { ${a.frames} }
`
}

const head = '// Generated by scripts/build.mjs from art/*.mjs: do not edit.\n'
const quote = (s) => `'${s}'`
function file(icons) {
  let out = `${head}import { icon } from '../svg'\nimport '../tiers.css'\n\nexport { iconSet } from '../set'\nexport type { IconComponent, IconProps } from '../svg'\nexport type { ActionIconProps, IconTrigger } from '../action'\n\n`
  for (const [name, entry] of Object.entries(icons)) {
    const f = forms(name, entry),
      X = exportName(name),
      S = title(name)
    out += `export const ${X} = /*#__PURE__*/ icon(${quote(f.hollow.line)},${quote(f.hollow.pixels)})\n`
    out += `export const ${X}Solid = /*#__PURE__*/ icon(${quote(f.solid.line)},${quote(f.solid.pixels)})\n`
    out += `export { ${X} as ${X}Hollow, ${X} as ${S}, ${X} as ${S}Hollow, ${X}Solid as ${S}Solid }\n`
    if (ACTIONS[name])
      out += `export { ${X}Action, ${X}Action as ${S}Action } from './actions/${name}'\n`
  }
  return out
}

export async function outputs() {
  const icons = await load()
  return {
    'all.tsx': file(icons),
    // the pack, for `import Icons from '@weft-js/warp-icons'`: its own file, since a module can't default-export itself to TypeScript
    'index.tsx': `${head}import * as pack from './all'\n\nexport * from './all'\nexport default pack\n`,
    'names.ts': `${head}export const names = ${JSON.stringify(Object.keys(icons))} as const\nexport type IconName = (typeof names)[number]\nexport type IconVariant = 'solid' | 'action'\nexport const actions = ${JSON.stringify(Object.keys(ACTIONS))} as const\nexport type IconActionName = (typeof actions)[number]\n`,
    ...Object.fromEntries(
      Object.keys(ACTIONS).flatMap((name) => {
        const { line, pixels } = acting(name, icons[name], ACTIONS[name])
        return [
          [
            `actions/${name}.tsx`,
            `${head}import { acting } from '../../action'\nimport '../../tiers.css'\nimport './${name}.css'\n\nexport const ${exportName(name)}Action = /*#__PURE__*/ acting(${quote(line)},${quote(pixels)})\n`,
          ],
          [`actions/${name}.css`, actionCss(name)],
        ]
      }),
    ),
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await outputs()
  const gen = new URL('../src/gen/', import.meta.url)
  const check = process.argv.includes('--check')
  mkdirSync(new URL('actions/', gen), { recursive: true })
  const stale = []
  for (const [f, text] of Object.entries(files)) {
    if (!check) {
      writeFileSync(new URL(f, gen), text)
      continue
    }
    let was = ''
    try {
      was = readFileSync(new URL(f, gen), 'utf8')
    } catch {}
    if (was !== text) stale.push(f)
  }
  if (stale.length) {
    console.error(`src/gen is stale (${stale.join(', ')}): run node scripts/build.mjs`)
    process.exit(1)
  }
  console.log(`${Object.keys(await load()).length} icons`)
}

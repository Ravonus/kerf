// art/*.mjs → src/gen/*: one file per tier and `all`, so a static tier compiles to that tier alone.
//   node scripts/build.mjs           write
//   node scripts/build.mjs --check   exit 1 if src/gen is stale
import { mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { outline, pixel } from './draw.mjs'

const dir = new URL('../art/', import.meta.url)
export async function load() {
  const out = {}
  for (const f of readdirSync(dir).filter(f => f.endsWith('.mjs')).sort()) {
    const set = (await import(new URL(f, dir))).default
    for (const [name, value] of Object.entries(set)) {
      if (out[name]) throw new Error(`${name} twice`)
      out[name] = value
    }
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)))
}
export const pascal = name => 'Icon' + name.replace(/(^|-)(.)/g, (_, __, c) => c.toUpperCase())

const PIX = 'fill="currentColor" stroke="none" transform="scale(1.5)" shape-rendering="crispEdges"'
const vivid = (p, t) => `<path${t} ${PIX} d="${p.ink}" />` + (p.shade ? `<path${t} ${PIX} fill-opacity=".4" d="${p.shade}" />` : '')

export function draw(name, [spec, art], tier) {
  const q = outline(spec, 'quiet'), b = outline(spec, 'balanced'), p = pixel(art, name)
  if (tier === 'quiet') return `<path d="${q.body + q.weft}" />`
  if (tier === 'balanced') return (b.body ? `<path d="${b.body}" />` : '') + (b.weft ? `<path data-w="" d="${b.weft}" />` : '')
  if (tier === 'vivid') return vivid(p, '')
  const pair = (x, y, w) => !x && !y ? '' : x === y ? `<path data-t="o"${w} d="${x}" />` : `<path data-t="q"${w} d="${x}" /><path data-t="b"${w} d="${y}" />`
  return pair(q.body, b.body, '') + pair(q.weft, b.weft, ' data-w=""') + vivid(p, ' data-t="v"')
}

const head = '// Generated by scripts/build.mjs from art/*.mjs: do not edit.\n'
function file(icons, tier) {
  let out = `${head}import { icon, type IconProps } from '../svg'\n\n`
  for (const [name, art] of Object.entries(icons)) out += `export const ${pascal(name)} = (p: IconProps) => icon(p, () => <>${draw(name, art, tier)}</>)\n`
  return out
}

export async function outputs() {
  const icons = await load()
  const files = {}
  for (const t of ['all', 'quiet', 'balanced', 'vivid']) files[`${t}.tsx`] = file(icons, t)
  files['names.ts'] = `${head}export const names = ${JSON.stringify(Object.keys(icons))} as const\nexport type IconName = (typeof names)[number]\n`
  return files
}

if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await outputs()
  const gen = new URL('../src/gen/', import.meta.url)
  const check = process.argv.includes('--check')
  mkdirSync(gen, { recursive: true })
  const stale = []
  for (const [f, text] of Object.entries(files)) {
    if (!check) { writeFileSync(new URL(f, gen), text); continue }
    let was = ''
    try { was = readFileSync(new URL(f, gen), 'utf8') } catch {}
    if (was !== text) stale.push(f)
  }
  if (stale.length) { console.error(`src/gen is stale (${stale.join(', ')}): run node scripts/build.mjs`); process.exit(1) }
  console.log(`${files['names.ts'].match(/","/g).length + 1} icons`)
}

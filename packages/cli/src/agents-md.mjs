// `weft agents-md`: AGENTS.md generated from the installed weft (exports, the codes its compiler reports) and this
// project's tasks. Under 8 KB (PLAN §7). Never edited by hand: `--check` fails when it is stale.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { sourceAlias } from './alias.mjs'
import { catalog } from './catalog.mjs'
import { commandsPage, installed, readDoc } from './docs.mjs'
import { loadConfig } from './load-config.mjs'
import { agentsSection } from './plugins.mjs'
import { tasks } from './tasks.mjs'

export const limit = 8 * 1024

/** `T001, T002, T003, P007` → `T001–T003, P007`: runs of consecutive codes as ranges (three or more). */
export function ranges(codes) {
  const out = []
  for (let i = 0; i < codes.length; ) {
    let j = i
    const num = c => Number(c.slice(1))
    while (j + 1 < codes.length && codes[j + 1][0] === codes[i][0] && num(codes[j + 1]) === num(codes[j]) + 1) j++
    out.push(j - i >= 2 ? `${codes[i]}–${codes[j]}` : codes.slice(i, j + 1).join(', '))
    i = j + 1
  }
  return out.join(', ')
}
/** PLAN §3.1 primitives an agent may reach for; listed as missing when the installed weft doesn't export them. */
const planned = ['state', 'derived', 'resource', 'Boundary', 'watch', 'onMount', 'onCleanup', 'context', 'defineState', 'flush', 'untrack', 'batch']
/** Commands AGENTS.md leaves to `weft tasks --json`: rarely run by hand, or taught in their own section. */
const elsewhere = new Set(['agents-md', 'doctor', 'mcp', 'plugins', 'start', 'style', 'surfaces', 'tasks', 'tokens'])
/** The app-facing part of subpaths whose other exports are helpers compiled code calls. */
const entryPoints = { '@weft-js/core/dom': ['render', 'hydrate'], '@weft-js/core/ssr': ['renderToString', 'renderToStringAsync'], '@weft-js/core/browser': ['online', 'visible', 'lifecycle', 'media', 'on', 'interval'] }

/** The Full stack section, with this app's alias for its source. */
function fullStack(root) {
  const alias = sourceAlias(root)
  const text = readDoc('start-short')
  return alias ? text.replaceAll('#/', alias) : text.replace(/ Import your own code as [^(]*\(`src\/server\/todos`\); generated files are/, ' Generated files are')
}

export async function agentsMd(root) {
  root = resolve(root)
  const info = installed(root)
  const list = await tasks(root)
  const sections = (await loadConfig(root)).contributions.filter(c => c.manifest.agents).map(c => agentsSection(c.manifest.agents))
  const core = info.exports['@weft-js/core'] ?? []
  const missing = planned.filter(n => !core.includes(n))

  // Style-group codes (D0xx, W060) and `weft style` belong to the Styling section, which only a weft with @weft-js/core/style gets.
  const styled = info.exports['@weft-js/core/style']?.includes('group')
  const dcodes = catalog.filter(e => /^D0/.test(e.code) && (e.by === 'cli' || info.status[e.code]?.implemented)).map(e => e.code).sort()
  const startApp = existsSync(join(root, 'src', 'routes'))
  const tcodes = catalog.filter(e => e.code.startsWith('T') && info.status[e.code]?.implemented).map(e => e.code)

  // with plugins: the `weft plugins` command and their sections; without, neither
  const page = sections => [
    `# AGENTS.md`,
    '',
    `<!-- Generated by \`weft agents-md\` from weft@${info.weft.version}. Do not edit: change weft.config.ts and regenerate. -->`,
    '',
    `This is a **weft** app. It is not React: components run once, state is a box, and`,
    `React hooks don't exist. Run \`weft check --json\` after every change; each diagnostic has a code, location, why and fix.`,
    '',
    'Start with `.weft/map.md` (`weft map`): what this app has and what to call for each part.',
    '',
    '## Rules',
    '',
    readDoc('rules'),
    ...(core.includes('resource')
      ? ['10. **Async data is `resource(signal => fetch(…))`** (`.value .pending .error .refresh()`), never `derived(async …)` (W012).',
         core.includes('Boundary') ? '    Show loading and errors with `<Boundary pending={…} error={(e, retry) => …}>`. More: `weft docs async`.' : '']
      : []),
    '',
    '**Leave props untyped**: `weft docs props`.',
    '',
    `## API in weft@${info.weft.version}`,
    '',
    `- \`weft\`: ${core.filter(n => planned.includes(n)).map(n => `\`${n}\``).join(', ')}` + (core.includes('state') ? ', `state.linked`' : ''),
    ...['@weft-js/core/dom', '@weft-js/core/ssr'].map((mod, i, all) => {
      const names = entryPoints[mod].filter(n => info.exports[mod]?.includes(n))
      const last = all.slice(i + 1).every(m => !entryPoints[m].some(n => info.exports[m]?.includes(n)))
      return names.length ? `- \`${mod}\`: ${names.map(n => `\`${n}\``).join(', ')}.${last ? ' The rest are for compiled code; never import them.' : ''}` : ''
    }).filter(Boolean),
    info.exports['@weft-js/core/browser'] ? `- \`@weft-js/core/browser\`: ${entryPoints['@weft-js/core/browser'].filter(n => info.exports['@weft-js/core/browser'].includes(n)).map(n => `\`${n}\``).join(', ')}. Create them in setup (W051); server-rendered \`media\` needs \`ssr\` (W054). More: \`weft docs browser\`; hover and press as state: \`weft docs ui-state\`.` : '',
    info.exports['@weft-js/core/surface'] ? '- `@weft-js/core/surface`: canvas and WebGL, never raw `<canvas>`: `weft docs surface`.' : '',
    info.exports['@weft-js/core/test'] ? `- \`@weft-js/core/test\`: ${info.exports['@weft-js/core/test'].filter(n => !['canvasCalls', 'cleanup', 'fakeMeasure', 'leaks'].includes(n)).map(n => `\`${n}\``).join(', ')}, and \`expect(fn).toTouchAtMost(n, { runs })\`. Query by role/label/text; \`user\` actions and \`clock.advance\` end in \`flush()\`, so never sleep or \`waitFor\`.` : '',
    missing.length ? `- Not in this version yet: ${missing.map(n => `\`${n}\``).join(', ')}. Don't import them.` : '',
    '',
    '## Diagnostics',
    '',
    '`weft docs <code>` explains one. Also flagged: raw `addEventListener`, `setInterval` or sockets with no cleanup (W050), and a `watch` that folds a stream (W052) or copies a live value into `state` (W056).',
    '',
    tcodes.length ? `Test checks (\`weft check\` on test files): ${ranges(tcodes)}. No assertion, tautologies, sleeps, \`container\`/selectors/test ids, mocking weft, snapshots, conditional \`expect\`, \`.only\`/\`.skip\`. A deliberate one needs \`// weft-allow T00x: <reason>\`.` : '',
    '',
    'Before a change is done, see it work in the running app (`weft browser snapshot|act|assert`, or `__weft__.agent` in your own browser) and run `weft test --gate`: new tests must fail on the old code and kill a mutant (T010, T011, T020). More: `weft docs verify`.',
    '',
    ...(startApp
      ? ['## Full stack', '', fullStack(root), '']
      : []),
    ...(styled
      ? ['## Styling',
         '',
         `**Run \`weft style find <what it is>\` first**, then reuse a group or add an axis value; never class lists. New: \`const card = group('card', { base: { pad: 'group' }, axes: { status: { late: { tone: 'critical' } } } })\` from \`@weft-js/core/style\`, \`<li {...card({ status })}>\`. Tokens only. ${ranges(dcodes)}, W060: \`weft docs style\`, \`weft docs design\`; \`weft fix\` applies the safe fixes.`,
         '']
      : []),
    '## Commands',
    '',
    commandsPage({ ...list, tasks: list.tasks.filter(t => !elsewhere.has(t.name)) }, { planned: false }),
    '',
    '`weft tasks --json` lists the rest.',
    '',
    ...(sections.length ? ['## Plugins', '', ...sections] : []),
    '## More',
    '',
    `\`weft docs <topic>\` or \`weft mcp\`: \`rules\`, \`props\`, \`lists\`, \`async\`, \`testing\`, \`browser\`, \`verify\`, ${startApp ? '`start`, ' : ''}${info.exports['@weft-js/core/style'] ? '`style`, ' : ''}${info.exports['@weft-js/core/surface'] ? '`surface`, ' : ''}\`config\`, \`diagnostics\`, \`commands\`.`,
    '',
  ]
    .filter((line, i, all) => !(line === '' && all[i - 1] === ''))
    .join('\n')

  const text = page(sections)
  const bytes = Buffer.byteLength(text)
  // the limit is weft's own text: plugin sections have their own 1 KB each (P112) on top
  return { path: join(root, 'AGENTS.md'), text, bytes, overLimit: Buffer.byteLength(page([])) > limit }
}

/** Write AGENTS.md, or with `check` only compare. Returns whether the file on disk was current. */
export async function writeAgentsMd(root, { check = false } = {}) {
  const out = await agentsMd(root)
  const current = existsSync(out.path) && readFileSync(out.path, 'utf8') === out.text
  if (!check && !current) writeFileSync(out.path, out.text)
  return { ...out, current, written: !check && !current }
}

// `weft agents-md`: AGENTS.md generated from the installed weft (exports, the codes its compiler reports) and this
// project's tasks. Under 8 KB (PLAN §7). Never edited by hand: `--check` fails when it is stale.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { catalog } from './catalog.mjs'
import { commandsPage, installed, readDoc } from './docs.mjs'
import { tasks } from './tasks.mjs'

export const limit = 8 * 1024
/** PLAN §3.1 primitives an agent may reach for; listed as missing when the installed weft doesn't export them. */
const planned = ['state', 'derived', 'resource', 'watch', 'onMount', 'onCleanup', 'context', 'defineState', 'flush', 'untrack', 'batch']

export async function agentsMd(root) {
  root = resolve(root)
  const info = installed(root)
  const list = await tasks(root)
  const core = info.exports.weft ?? []
  const missing = planned.filter(n => !core.includes(n))

  const reported = catalog.filter(e => e.by === 'compiler' && info.status[e.code]?.implemented && e.code !== 'W000')
  const notYet = catalog.filter(e => e.by === 'compiler' && !info.status[e.code]?.implemented).map(e => e.code)
  const pcodes = catalog.filter(e => e.by === 'cli').map(e => e.code)

  const text = [
    `# AGENTS.md`,
    '',
    `<!-- Generated by \`weft agents-md\` from weft@${info.weft.version}. Do not edit: change weft.config.ts and regenerate. -->`,
    '',
    `This is a **weft** app (fine-grained reactive TSX). It is not React: components run once, state is a box, and`,
    `React hooks don't exist. Run \`weft check --json\` after every change; each diagnostic has a code, a location, why, and a fix.`,
    '',
    '## Rules',
    '',
    readDoc('rules'),
    '',
    `## API in weft@${info.weft.version}`,
    '',
    `- \`weft\`: ${core.filter(n => planned.includes(n)).map(n => `\`${n}\``).join(', ')}` + (core.includes('state') ? ', `state.linked`' : ''),
    info.exports['weft/dom']?.includes('render') ? '- `weft/dom`: `render(() => <App />, el)`. Its other exports are helpers compiled code calls; never import them.' : '',
    info.exports['weft/test'] ? `- \`weft/test\`: ${info.exports['weft/test'].map(n => `\`${n}\``).join(', ')}, and \`expect(fn).toTouchAtMost(n, { runs })\`` : '',
    missing.length ? `- Not in this version yet: ${missing.map(n => `\`${n}\``).join(', ')}. Don't import them.` : '',
    '',
    '## Diagnostics this weft reports',
    '',
    '| Code | Catches | Fix |',
    '|---|---|---|',
    ...reported.map(e => `| ${e.code} | ${e.catches} | ${e.fix}${info.status[e.code].autofix ? ' (autofix)' : info.status[e.code].suggestion ? ' (suggested edit)' : ''} |`),
    '',
    `Project checks: ${pcodes.join(', ')}. In the catalog but not reported yet: ${notYet.join(', ')}. \`weft docs <code>\` explains any code.`,
    '',
    '## Commands',
    '',
    commandsPage(list),
    '',
    '## More',
    '',
    '`weft docs <topic>` or the `docs` tool of `weft mcp`: `rules`, `props`, `lists`, `testing`, `config`, `diagnostics`, `commands`.',
    '',
  ]
    .filter((line, i, all) => !(line === '' && all[i - 1] === ''))
    .join('\n')

  const bytes = Buffer.byteLength(text)
  return { path: join(root, 'AGENTS.md'), text, bytes, overLimit: bytes > limit }
}

/** Write AGENTS.md, or with `check` only compare. Returns whether the file on disk was current. */
export async function writeAgentsMd(root, { check = false } = {}) {
  const out = await agentsMd(root)
  const current = existsSync(out.path) && readFileSync(out.path, 'utf8') === out.text
  if (!check && !current) writeFileSync(out.path, out.text)
  return { ...out, current, written: !check && !current }
}

// `kerf agents-md`: AGENTS.md generated from the installed kerf (exports, the codes its compiler reports) and this
// project's tasks. Under 9 KB (PLAN §7, raised from 8 KB in 2026-11). Never edited by hand: `--check` fails when it is stale.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { sourceAlias } from './alias.mjs'
import { catalog } from './catalog.mjs'
import { commandsPage, installed, readDoc } from './docs.mjs'
import { loadConfig } from './load-config.mjs'
import { agentsSection } from './contributions.mjs'
import { tasks } from './tasks.mjs'

export const limit = 9 * 1024

/** `T001, T002, T003, P007` → `T001–T003, P007`: runs of consecutive codes as ranges (three or more). */
export function ranges(codes) {
  const out = []
  for (let i = 0; i < codes.length;) {
    let j = i
    const num = (c) => Number(c.slice(1))
    while (
      j + 1 < codes.length &&
      codes[j + 1][0] === codes[i][0] &&
      num(codes[j + 1]) === num(codes[j]) + 1
    )
      j++
    out.push(j - i >= 2 ? `${codes[i]}–${codes[j]}` : codes.slice(i, j + 1).join(', '))
    i = j + 1
  }
  return out.join(', ')
}
/** PLAN §3.1 primitives an agent may reach for; listed as missing when the installed kerf doesn't export them. */
const planned = [
  'state',
  'derived',
  'resource',
  'Boundary',
  'watch',
  'onMount',
  'onCleanup',
  'context',
  'defineState',
  'flush',
  'untrack',
  'batch',
]
/** Commands AGENTS.md leaves to `kerf tasks --json`: rarely run by hand, or taught in their own section. */
const elsewhere = new Set([
  'agents-md',
  'doctor',
  'mcp',
  'plugins',
  'start',
  'style',
  'surfaces',
  'tasks',
  'tokens',
])
/** The app-facing part of subpaths whose other exports are helpers compiled code calls. */
const entryPoints = {
  '@kerf/core/dom': ['render', 'hydrate'],
  '@kerf/core/ssr': ['renderToString', 'renderToStringAsync'],
  '@kerf/core/browser': ['online', 'visible', 'lifecycle', 'media', 'on', 'interval'],
}

/** The Full stack section, with this app's alias for its source. */
function fullStack(root) {
  const alias = sourceAlias(root)
  const text = readDoc('start-short')
  return alias
    ? text.replaceAll('#/', alias)
    : text.replace(
        / Import your own code as [^(]*\(`src\/server\/todos`\); generated files are/,
        ' Generated files are',
      )
}

/** This project's AGENTS.md, written from what the installed kerf reports: the text, where it goes, and whether kerf's own part is over the limit. */
export async function agentsMd(root) {
  root = resolve(root)
  const info = installed(root)
  const list = await tasks(root)
  const sections = (await loadConfig(root)).contributions
    .filter((c) => c.manifest.agents)
    .map((c) => agentsSection(c.manifest.agents))
  const core = info.exports['@kerf/core'] ?? []
  const missing = planned.filter((n) => !core.includes(n))

  // Style-group codes (D0xx, W060) and `kerf style` belong to the Styling section, which only a kerf with @kerf/core/style gets.
  const styled = info.exports['@kerf/core/style']?.includes('group')
  const dcodes = catalog
    .filter((e) => e.code.startsWith('D0') && (e.by === 'cli' || info.status[e.code]?.implemented))
    .map((e) => e.code)
    .sort()
  const startApp = existsSync(join(root, 'src', 'routes'))
  const tcodes = catalog
    .filter((e) => e.code.startsWith('T') && info.status[e.code]?.implemented)
    .map((e) => e.code)

  const text = page({ root, info, core, missing, tcodes, startApp, styled, dcodes, list }, sections)
  const bytes = Buffer.byteLength(text)
  // the limit is kerf's own text: plugin sections have their own 1 KB each (P112) on top
  return {
    path: join(root, 'AGENTS.md'),
    text,
    bytes,
    overLimit:
      Buffer.byteLength(
        page({ root, info, core, missing, tcodes, startApp, styled, dcodes, list }, []),
      ) > limit,
  }
}

function pageIntro({ root, info, core, missing }) {
  return [
    `# AGENTS.md`,
    '',
    `<!-- Generated by \`kerf agents-md\` from kerf@${info.kerf.version}. Do not edit: change kerf.config.ts and regenerate. -->`,
    '',
    `This is a **kerf** app. It is not React: components run once, state is a box, and`,
    `React hooks don't exist. Run \`kerf check --json\` after every change; each diagnostic gives code, location, why and fix.`,
    '',
    'Start with `.kerf/map.md` (`kerf map`): what this app has and what to call.',
    ...(existsSync(join(root, 'src', 'theme.css'))
      ? ['', "`src/theme.css` is this app's CSS; `kerf docs theme` changes the look."]
      : []),
    '',
    '## Rules',
    '',
    readDoc('rules'),
    ...(core.includes('resource')
      ? [
          '10. **Async data is `resource(signal => fetch(…))`** (`.value .pending .error .refresh()`), never `derived(async …)` (W012).',
          core.includes('Boundary')
            ? '    Loading and errors: `<Boundary pending={…} error={(e, retry) => …}>`.'
            : '',
        ]
      : []),
    '',
    '**Leave props untyped**: `kerf docs props`.',
    '',
    `## API in kerf@${info.kerf.version}`,
    '',
    `- \`@kerf/core\`: ${core
      .filter((n) => planned.includes(n))
      .map((n) => `\`${n}\``)
      .join(', ')}` + (core.includes('state') ? ', `state.linked`' : ''),
    ...['@kerf/core/dom', '@kerf/core/ssr']
      .map((mod, i, all) => {
        const names = entryPoints[mod].filter((n) => info.exports[mod]?.includes(n))
        const last = all
          .slice(i + 1)
          .every((m) => !entryPoints[m].some((n) => info.exports[m]?.includes(n)))
        return names.length
          ? `- \`${mod}\`: ${names.map((n) => `\`${n}\``).join(', ')}.${last ? ' Never import the rest.' : ''}`
          : ''
      })
      .filter(Boolean),
    info.exports['@kerf/core/browser']
      ? `- \`@kerf/core/browser\`: ${entryPoints['@kerf/core/browser']
          .filter((n) => info.exports['@kerf/core/browser'].includes(n))
          .map((n) => `\`${n}\``)
          .join(
            ', ',
          )}. Create them in setup (W051); server-rendered \`media\` needs \`ssr\` (W054). More: \`kerf docs browser\`; hover and press as state: \`kerf docs ui-state\`.`
      : '',
    info.exports['@kerf/core/surface']
      ? '- `@kerf/core/surface`: canvas and WebGL, never raw `<canvas>`: `kerf docs surface`.'
      : '',
    info.exports['@kerf/core/test']
      ? `- \`@kerf/core/test\`: ${info.exports['@kerf/core/test']
          .filter((n) => !['canvasCalls', 'cleanup', 'fakeMeasure', 'leaks'].includes(n))
          .map((n) => `\`${n}\``)
          .join(
            ', ',
          )}, and \`expect(fn).toTouchAtMost(n, { runs })\`. Query by role/label/text; \`user\` actions and \`clock.advance\` end in \`flush()\`, so never sleep or \`waitFor\`.`
      : '',
    missing.length
      ? `- Not in this version yet: ${missing.map((n) => `\`${n}\``).join(', ')}. Don't import them.`
      : '',
    '',
  ]
}

// with plugins: the `kerf plugins` command and their sections; without, neither
function page({ root, info, core, missing, tcodes, startApp, styled, dcodes, list }, plugins) {
  return [
    ...pageIntro({ root, info, core, missing }),
    '## Diagnostics',
    '',
    '`kerf docs <code>` explains one. Also flagged: an early `return` in a `.map` callback (W013), raw `addEventListener`, `setInterval` or sockets with no cleanup (W050), and a `watch` that folds a stream (W052) or copies a live value into `state` (W056).',
    '',
    tcodes.length
      ? `Test checks (\`kerf check\` on test files): ${ranges(tcodes)}. No assertion, tautologies, sleeps, \`container\`/selectors/test ids, mocking kerf, snapshots, conditional \`expect\`, \`.only\`/\`.skip\`. To allow one: \`// kerf-allow T00x: <reason>\`.`
      : '',
    '',
    "Before a change is done, see it work (`kerf browser snapshot|act|assert`, or `__kerf__.agent` in your own browser) and run `kerf test --gate`: new tests must fail on the old code and kill a mutant (T010, T011, T020). `kerf build` ends by auditing the pages it built at a phone's and a desktop's width (L-codes: names, contrast, console, the head, sideways scroll, layout shift) and fails on an error; `kerf audit --url <deploy>` checks a live site. More: `kerf docs verify`.",
    '',
    'Before publishing, choose `build.audit.indexing`: `public` makes noindex an error; `private` preserves intentional exclusions. Audit the actual deployed URL with `kerf audit --url <url> --indexing public` for public search: a proxy header can override correct markup. Never remove private indexing directives just to improve a score.',
    '',
    ...(startApp ? ['## Full stack', '', fullStack(root), ''] : []),
    ...(styled
      ? [
          '## Styling',
          '',
          `**Run \`kerf style find <what it is>\` first**, then reuse a group or add an axis value; never class lists. New: \`const card = group('card', { base: { pad: 'group' }, axes: { status: { late: { tone: 'critical' } } } })\` from \`@kerf/core/style\`, \`<li {...card({ status })}>\`. Tokens only. ${ranges(dcodes)}, W060: \`kerf docs style\`, \`kerf docs design\`; \`kerf fix\` applies the safe fixes.`,
          '',
        ]
      : []),
    '## Commands',
    '',
    commandsPage(
      { ...list, tasks: list.tasks.filter((t) => !elsewhere.has(t.name)) },
      { planned: false },
    ),
    '',
    '`kerf tasks --json` lists the rest.',
    '',
    ...(plugins.length ? ['## Plugins', '', ...plugins] : []),
    '## More',
    '',
    `\`kerf docs <topic>\` or \`kerf mcp\`: \`rules\`, \`props\`, \`lists\`, \`async\`, \`testing\`, \`browser\`, \`verify\`, ${startApp ? '`start`, ' : ''}${info.exports['@kerf/core/style'] ? '`style`, ' : ''}${info.exports['@kerf/core/surface'] ? '`surface`, ' : ''}\`config\`, \`diagnostics\`, \`commands\`.`,
    '',
  ]
    .filter((line, i, all) => !(line === '' && all[i - 1] === ''))
    .join('\n')
}

/** Write AGENTS.md, or with `check` only compare. Returns whether the file on disk was current. */
export async function writeAgentsMd(root, { check = false } = {}) {
  const out = await agentsMd(root)
  const current = existsSync(out.path) && readFileSync(out.path, 'utf8') === out.text
  if (!check && !current) writeFileSync(out.path, out.text)
  return { ...out, current, written: !check && !current }
}

// The client (`client.tsx` starts it) and its router (research 25 §3): hydrate the server's page, then navigate without page loads. A navigation
// fetches `/_kerf/data/<path>` (the server matches, runs the loaders and merges the head, so loaders never ship to
// the client), loads the route chunks it needs (started in parallel from a guess against the route table), and
// writes the levels: a level that keeps its route keeps its component and gets new params/data in place.
// `setHead` writes the server's merged tags for the tab title and history; crawlers only read the server's HTML.
//
// Server functions (research 27): the query cache seeds itself from the page's `#kerf-cache` as it loads, and gets
// each navigation's `c` through `client.seed`, so hydration fetches nothing (and an app without queries doesn't ship
// the cache). Redirects from loaders and server functions navigate (at most 5 in a row); a
// mutation that invalidates a tag the current route's loaders read refetches the route data in place.

import { client, type Component } from './router'
import type { RouteDataSchema, ShellMeta } from './shell'
import type { ShellConfig, ShellRoute } from './shell/routes'
import { mount, prepare } from './run/boot'
import { listeners } from './run/listeners'
import { Navigation } from './run/navigation'
import { prepareRouteShape } from './run/shape-preparation'
import { isErrorRoute, LATE_ERROR, type RouteErrorData } from './failure'
import { clientFailure, failOutlet, type LateFailure } from './run/failure'

type Hot = ImportMeta & {
  hot?: { on(event: string, on: (data: { queries: boolean }) => unknown): void }
}

/**
 * Synchronous shape metadata from separately compiled modules. CSS and emitted
 * asset bytes are null until known; consumers must not treat them as available
 * or free. cssText holds generated groups and resolved static entry and level
 * styles, including tokens. cssStatus remains partial.
 * Unavailable covers unproven overrides and unsupported route files.
 */
export type RouteShape =
  | { kind: 'disabled'; css: string[] | null; bytes: number | null }
  | {
      kind: 'unavailable'
      reason: 'unresolved-export' | 'unsupported-file' | 'missing-shape'
      css: null
      bytes: null
    }
  | {
      kind: 'generated' | 'override'
      component: Component
      css: string[] | null
      cssText: string[]
      cssStatus: 'partial'
      bytes: number | null
      /** A generated shape with no structure of its own (`$kerfShapeThin`): the router stands in for it. */
      thin?: boolean
    }

/** Shape entries are keyed by level id, including layouts and error routes. */
export type RouteShapes = Record<string, RouteShape>

/** The client half of `virtual:kerf/routes`: the page routes in match order, and a chunk loader per route id. */
export interface ClientRoutes {
  build?: string | null
  table: ShellRoute[]
  /** Release configuration for hydration-free, data-only rendering. */
  shell?: ShellConfig
  load: Record<string, () => Promise<ClientRouteModule>>
  /** Load a failed route entry at a fresh module URL. Generated by Start's Vite plugin. */
  retryLoad?: Record<string, () => Promise<ClientRouteModule>>
  /** Eager shape metadata, keyed by route or layout id. */
  shapes?: RouteShapes
  /** Loads the shapes' stylesheet text, in a build: the router calls it once the page is up. */
  shapeStyles?: () => Promise<unknown>
  /** Each island's code, by id: all a static level loads (PLAN §11). */
  islands?: Record<string, () => Promise<{ default: Component }>>
}

/** The browser-side exports of a route level. */
export interface ClientRouteModule {
  default?: Component
  routeData?: RouteDataSchema
  meta?: ShellMeta
}

/** Hydrate the page in `#app` and take over its links. Resolves once hydrated. */
export async function start(
  routes: ClientRoutes,
  options: { container?: Element; shell?: boolean } = {},
) {
  const prepared = prepare(routes, options)
  const failed = await prepared.loaded
  const page = mount(prepared)
  page.route.prepareShape = (id) => prepareRouteShape(routes, id, document)
  void routes.shapeStyles?.().catch(() => {})
  const navigation = new Navigation(routes, page)
  client.navigate = navigation.go
  if (failed) {
    const match = prepared.page.m[failed.depth]
    const data =
      match && isErrorRoute(match.id) ? (match.data as RouteErrorData) : clientFailure(failed.cause)
    void failOutlet(navigation, failed.depth, data)
  }
  const late = () => {
    const signal = document.getElementById(LATE_ERROR)
    if (!signal) return
    if (navigation.current || navigation.matches !== prepared.page.m) return signal.remove()
    const failure: LateFailure = JSON.parse(signal.textContent)
    void failOutlet(navigation, failure.depth, failure.data).finally(() => signal.remove())
  }
  addEventListener(LATE_ERROR, late)
  late()
  listeners(navigation, prepared.page.p, options.shell, () => (import.meta as Hot).hot)
  // The router follows links from here: the browser's prefetching for full loads (capture.ts `speculate`) stops.
  document.getElementById('kerf-speculate')?.remove()
  if (options.shell) {
    // The page in the document stands in for every address: go to the one the visitor asked for.
    navigation.shell = true
    void navigation.go(location.href, { arrive: true, scroll: false })
  }
  return page.route
}
